#!/usr/bin/env python3
"""Repo bakım yapılandırmasını .claude/ kaynağından .codex/ altına üretir.

Python 3.11+, yalnız standart kütüphane. --check yazmaz; --watch kaynakları izler.
Kullanıcı dosyalarını veya elle değiştirilmiş çıktıları sessizce ezmez.
"""
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import signal
import sys
import time
import tomllib

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ".codex/.claude-sync.json"
HEADER = "# Generated by scripts/sync-claude-codex.py; edit .claude/ sources instead.\n"
ADAPTER = """Codex execution: use the available file-reading, search, shell and editing tools for the
capabilities called Read, Grep, Glob, Bash, Edit and Write in the source instructions.
Claude frontmatter/tool/model checks below describe the source files being audited,
not Codex runtime settings. Inherit the session's Codex model. Preserve all file-ownership,
read-only, full-read and no-delegation limits below.

"""


def digest(content):
    return hashlib.sha256(content.encode()).hexdigest()


def toml_string(value):
    # Literal multiline strings preserve regex backslashes; JSON handles embedded '''.
    if "'''" not in value and not any(ord(c) < 32 and c not in "\n\t" for c in value):
        return "'''\n" + value + "'''"
    return json.dumps(value, ensure_ascii=False)


def agent_config(path, content):
    lines = content.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path}: frontmatter eksik")
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        raise ValueError(f"{path}: frontmatter kapanışı eksik") from None
    meta = {}
    for line in lines[1:end]:
        if not line.strip():
            continue
        key, sep, value = line.partition(":")
        if not sep or key in meta or key not in {"name", "description", "model", "tools"}:
            raise ValueError(f"{path}: desteklenmeyen/tekrarlanan frontmatter: {key}")
        value = value.strip()
        if value in {"|", ">", "|-", ">-"}:
            raise ValueError(f"{path}: metadata tek satırlı olmalı: {key}")
        if value.startswith('"'):
            value = json.loads(value)
        elif value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("''", "'")
        if not isinstance(value, str):
            raise ValueError(f"{path}: metadata metin olmalı: {key}")
        meta[key] = value
    if any(not meta.get(key) for key in ("name", "description", "model", "tools")):
        raise ValueError(f"{path}: name, description, model ve tools gerekli")
    if meta["name"] != Path(path).stem or not re.fullmatch(r"[a-z][a-z0-9-]*", meta["name"]):
        raise ValueError(f"{path}: name dosya adıyla eşleşmeli")
    capabilities = {t.strip() for t in meta["tools"].split(",")}
    if capabilities - {"Read", "Grep", "Glob", "Bash", "Edit", "Write", "NotebookEdit"}:
        raise ValueError(f"{path}: yeni araç için Codex eşlemesi gerekli")
    sandbox = "workspace-write" if capabilities & {"Edit", "Write", "NotebookEdit"} else "read-only"
    body = ADAPTER + "".join(lines[end + 1:]).strip() + "\n"
    result = HEADER + f"# Source: {path}\n"
    result += f'name = {json.dumps(meta["name"], ensure_ascii=False)}\n'
    result += f'description = {json.dumps(meta["description"], ensure_ascii=False)}\n'
    result += f'sandbox_mode = "{sandbox}"\n'
    result += "developer_instructions = " + toml_string(body) + "\n"
    assert tomllib.loads(result)["developer_instructions"] == body
    return result


def convert_hook(source):
    # Keep the source algorithm and selectors; adapt only client-specific details.
    replacements = {
        '"kit-review-gate"': '"codex-kit-review-gate"',
        "Agent aracıyla": "Codex alt-agent aracıyla",
        'CHANGELOG = "CHANGELOG.md"': (
            'LINT += (".claude/agents/", ".codex/agents/")\n'
            'DOCS += (".codex/agents/", ".claude/settings.json", ".codex/hooks.json")\n'
            'CHANGELOG = "CHANGELOG.md"'
        ),
    }
    for old, new in replacements.items():
        if source.count(old) != 1:
            raise ValueError(f"kit-review-gate.py yapısı değişti; Codex uyarlamasını güncelle: {old}")
        source = source.replace(old, new)
    source = source.replace(".git/kit-review-gate/", ".git/codex-kit-review-gate/")
    result = HEADER + "# Source: .claude/hooks/kit-review-gate.py\n" + source
    compile(result, ".codex/hooks/kit-review-gate.py", "exec")
    return result


def build(root):
    source_root = root / ".claude"
    if not source_root.is_dir() or source_root.is_symlink():
        raise ValueError(".claude kaynak dizini yok veya sembolik bağ")
    sources, outputs = {}, {}
    for path in sorted(source_root.rglob("*")):
        if "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        if path.is_symlink():
            raise ValueError(f"Sembolik kaynak desteklenmiyor: {path}")
        if not path.is_file():
            continue
        relative = path.relative_to(root).as_posix()
        content = path.read_text(encoding="utf-8")
        sources[relative] = content
        if path.parent == source_root / "agents" and path.suffix == ".md":
            outputs[f".codex/agents/{path.stem}.toml"] = agent_config(relative, content)
        elif relative == ".claude/hooks/kit-review-gate.py":
            outputs[".codex/hooks/kit-review-gate.py"] = convert_hook(content)
        elif relative != ".claude/settings.json":
            raise ValueError(f"Codex dönüşümü tanımlanmamış kaynak: {relative}")
    if ".claude/settings.json" not in sources:
        raise ValueError(".claude/settings.json gerekli")
    settings = json.loads(sources[".claude/settings.json"])
    if not isinstance(settings, dict) or set(settings) != {"hooks"}:
        raise ValueError("settings.json: yalnız hooks alanının dönüşümü destekleniyor")
    hooks = settings["hooks"]
    if not isinstance(hooks, dict) or set(hooks) - {"Stop"}:
        raise ValueError("settings.json: yalnız Stop olayı destekleniyor")
    groups = hooks.get("Stop", [])
    if not isinstance(groups, list):
        raise ValueError("Stop bir liste olmalı")
    original = 'python3 "$CLAUDE_PROJECT_DIR/.claude/hooks/kit-review-gate.py"'
    replacement = 'python3 "$(git rev-parse --show-toplevel)/.codex/hooks/kit-review-gate.py"'
    for group in groups:
        if not isinstance(group, dict) or set(group) != {"hooks"} or not isinstance(group["hooks"], list):
            raise ValueError("Stop hook grubu için yeni eşleme gerekli")
        for hook in group["hooks"]:
            if not isinstance(hook, dict) or set(hook) - {"type", "command", "timeout"}:
                raise ValueError("Stop hook alanları için yeni eşleme gerekli")
            if hook.get("type") != "command" or hook.get("command") != original:
                raise ValueError("Desteklenmeyen Stop komutu; Codex eşlemesi gerekli")
            if "timeout" in hook and (type(hook["timeout"]) is not int or not 0 <= hook["timeout"] < 2**64):
                raise ValueError("Stop timeout, 0 ile 2**64-1 arasında bir tam sayı olmalı")
            if ".codex/hooks/kit-review-gate.py" not in outputs:
                raise ValueError("Stop hook kaynak dosyası eksik")
            hook["command"] = replacement
    outputs[".codex/hooks.json"] = json.dumps(settings, indent=2, ensure_ascii=False) + "\n"
    manifest = {"version": 1, "sources": {p: digest(c) for p, c in sources.items()},
                "outputs": {p: digest(c) for p, c in sorted(outputs.items())}}
    outputs[MANIFEST] = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    return outputs


def target(root, name):
    parts = PurePosixPath(name).parts
    if not parts or parts[0] != ".codex" or ".." in parts:
        raise ValueError(f"Geçersiz çıktı yolu: {name}")
    path = root
    for part in parts:
        path = path / part
        if path.is_symlink():
            raise ValueError(f"Sembolik hedefe yazılmaz: {path}")
        if path.exists() and path != root.joinpath(*parts) and not path.is_dir():
            raise ValueError(f"Çıktı üst yolu dizin değil: {path}")
    return path


def sync(root, check=False):
    outputs = build(root)  # Validate every input before changing any output.
    manifest_path = target(root, MANIFEST)
    previous = {}
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if not isinstance(manifest, dict) or manifest.get("version") != 1 or not isinstance(manifest.get("outputs"), dict):
            raise ValueError("Geçersiz .claude-sync.json manifesti")
        previous = manifest["outputs"]
    changed, removed = {}, []
    for name in sorted(set(outputs) | set(previous)):
        path = target(root, name)
        actual = path.read_text(encoding="utf-8") if path.exists() else None
        expected = outputs.get(name)
        if actual == expected:
            continue
        if not check and actual is not None and name != MANIFEST and digest(actual) != previous.get(name):
            raise ValueError(f"Kullanıcı dosyası/elle değişmiş çıktı korunuyor: {name}; farkı kaynağa taşı veya dosyayı yedekleyip kaldır")
        if expected is None:
            removed.append(name)
        else:
            changed[name] = expected
    if check:
        if changed or removed:
            print(".codex/ güncel değil:\n- " + "\n- ".join([*changed, *removed]))
            return 1
        print(".codex/ bakım çıktıları güncel.")
        return 0
    # Yazma adımı bölünmez: Ctrl+C çıktılar ile manifest arasına girerse .codex/ tutarsız kalır (--watch'ta yarış).
    # Kesinti, bütün dosyalar yazılana kadar ertelenir ve sonra yeniden yükseltilir.
    interrupted = []
    try:
        previous_handler = signal.signal(signal.SIGINT, lambda *_: interrupted.append(True))
    except ValueError:  # ana iş parçacığı dışında sinyal işleyici kurulamaz
        previous_handler = None
    try:
        for name in removed:
            target(root, name).unlink()
        for name in sorted(changed, key=lambda name: (name == MANIFEST, name)):
            content = changed[name]
            path = target(root, name)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    finally:
        if previous_handler is not None:
            signal.signal(signal.SIGINT, previous_handler)
    if interrupted:
        raise KeyboardInterrupt
    print(f".codex/: {len(changed)} dosya güncellendi, {len(removed)} eski çıktı kaldırıldı.", flush=True)
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Yazmadan güncellik denetle")
    mode.add_argument("--watch", action="store_true", help=".claude değiştikçe yeniden üret; Ctrl+C ile durdur")
    args = parser.parse_args()
    try:
        snapshot = build(ROOT) if args.watch else None
        result = sync(ROOT, check=args.check)
        if args.watch:
            print(".claude/ izleniyor (1 saniye aralıkla).", flush=True)
            while True:
                time.sleep(1)
                current = build(ROOT)
                if current != snapshot:
                    sync(ROOT)
                    snapshot = current
        return result
    except KeyboardInterrupt:
        return 0
    except (ValueError, OSError, TypeError, KeyError, SyntaxError) as exc:
        print(f"Codex senkronizasyonu durdu: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
